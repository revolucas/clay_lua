local function C(c) return c.r, c.g, c.b, c.a end

function layout(dt)
  local longText =
    "Hello world! This is a [i]sentence[/i] that should wrap nicely after around 200 pixels. But does it? Is it working?"

  -- LEFT
  clay.element("LeftAlignContainer")
    :layoutDirection(clay.TOP_TO_BOTTOM)
    :width(clay.SIZING_FIXED, 200)
    :height(clay.SIZING_FIT)
    :childGap(10)
    :childAlignment(clay.ALIGN_X_LEFT, clay.ALIGN_Y_TOP)
    :children(function()
      clay.text("LEFT ALIGNED:")
        :fontSize(14)
        :textColor(150, 150, 150, 255)
        :done()

      clay.element("LeftTextBox")
        :width(clay.SIZING_FIXED, 200)
        :height(clay.SIZING_FIT)
        :padding(10)
        :childAlignment(clay.ALIGN_X_LEFT, clay.ALIGN_Y_TOP)
        :backgroundColor(50, 50, 50, 255)
        :borderColor(100, 100, 100, 255)
        :borderWidth(1)
        :children(function()
          clay.text(longText)
            :fontId(1)
            :fontSize(16)
            :textColor(C(COLOR_WHITE))
            :wrapMode(clay.TEXT_WRAP_WORDS)
            :textAlignment(clay.TEXT_ALIGN_LEFT)
            :done()
        end)
    end)

  -- CENTER
  clay.element("CenterAlignContainer")
    :layoutDirection(clay.TOP_TO_BOTTOM)
    :width(clay.SIZING_FIXED, 200)
    :height(clay.SIZING_FIT)
    :childGap(10)
    :childAlignment(clay.ALIGN_X_CENTER, clay.ALIGN_Y_TOP)
    :children(function()
      clay.text("CENTER ALIGNED:")
        :fontSize(14)
        :textColor(150, 150, 150, 255)
        :done()

      clay.element("CenterTextBox")
        :width(clay.SIZING_FIXED, 200)
        :height(clay.SIZING_FIT)
        :padding(10)
        :childAlignment(clay.ALIGN_X_CENTER, clay.ALIGN_Y_TOP)
        :backgroundColor(50, 50, 50, 255)
        :borderColor(100, 100, 100, 255)
        :borderWidth(1)
        :children(function()
          clay.text(longText)
            :fontId(1)
            :fontSize(16)
            :textColor(C(COLOR_WHITE))
            :wrapMode(clay.TEXT_WRAP_WORDS)
            :textAlignment(clay.TEXT_ALIGN_CENTER)
            :done()
        end)
    end)

  -- RIGHT
  clay.element("RightAlignContainer")
    :layoutDirection(clay.TOP_TO_BOTTOM)
    :width(clay.SIZING_FIXED, 200)
    :height(clay.SIZING_FIT)
    :childGap(10)
    :childAlignment(clay.ALIGN_X_RIGHT, clay.ALIGN_Y_TOP)
    :children(function()
      clay.text("RIGHT ALIGNED:")
        :fontSize(14)
        :textColor(150, 150, 150, 255)
        :done()

      clay.element("RightTextBox")
        :width(clay.SIZING_FIXED, 200)
        :height(clay.SIZING_FIT)
        :padding(10)
        :childAlignment(clay.ALIGN_X_RIGHT, clay.ALIGN_Y_TOP)
        :backgroundColor(50, 50, 50, 255)
        :borderColor(100, 100, 100, 255)
        :borderWidth(1)
        :children(function()
          clay.text(longText)
            :fontId(1)
            :fontSize(16)
            :textColor(C(COLOR_WHITE))
            :wrapMode(clay.TEXT_WRAP_WORDS)
            :textAlignment(clay.TEXT_ALIGN_RIGHT)
            :done()
        end)
    end)
end
